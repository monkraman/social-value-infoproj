"""The tables layer (scope §4): facts imported from the Monk Spaces workbook.

`tables.json` is generated by scripts/import_workbook.py — never edit it by hand.
"""
import json
from functools import lru_cache
from pathlib import Path

TABLES_PATH = Path(__file__).with_name("tables.json")


@lru_cache(maxsize=1)
def load_tables() -> dict:
    return json.loads(TABLES_PATH.read_text(encoding="utf-8"))

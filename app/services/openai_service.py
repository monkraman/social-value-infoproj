    def generate_recommendation_with_conversation(
        self,
        context_text: str,
        opportunity: Dict[str, Any],
        toms_catalog: List[Dict[str, Any]],
        conversation_turns: List[Dict[str, Any]]
    ) -> Dict[str, Any]:
        """
        Context-aware multi-turn generation.
        `conversation_turns` is a list of dicts:
          [
            {"role": "user",      "content": "Original prompt text"},
            {"role": "assistant", "content": "Summary of turn-1 result JSON"},
            {"role": "user",      "content": "User feedback: add more Net Zero focus"},
            {"role": "assistant", "content": "Summary of turn-2 result JSON"},
            ...
            {"role": "user",      "content": "Latest feedback message"}
          ]
        The AI receives the full thread and uses ALL prior context to generate
        an improved proposal.
        """
        provider = settings.active_provider

        contract_val = float(opportunity.get('contract_value_gbp', 10000000.0))
        weighting_pct = float(opportunity.get('social_value_weighting_percent', 10.0))
        duration_yrs = int(opportunity.get('contract_duration_years', 3))
        target_sv_gbp = round(contract_val * (weighting_pct / 100.0), 2)
        loc = opportunity.get('location') or 'Regional'
        priorities_str = ', '.join(opportunity.get('priorities', [])) or 'Digital Inclusion, Skills Gaps & Youth Employment'

        system_prompt = (
            "You are the Infosys Social Value RFP Response Architect for UK public sector bids with perfect memory of this conversation.\n"
            "You are in a MULTI-TURN conversation with a bid author who is iteratively improving a Social Value proposal.\n\n"
            f"MANDATED TENDER TARGET: £{contract_val:,.0f} contract, {duration_yrs} yrs, {weighting_pct}% SV Weighting.\n"
            f"Target Social Value Creation: £{target_sv_gbp:,.2f}.\n"
            f"Client Priorities: {priorities_str} in {loc}.\n\n"
            "PROPORTIONAL VOLUME SIZING REQUIREMENTS:\n"
            f"- 'core_package': In-house & levy-focused baseline option delivering 100% of target (£{target_sv_gbp:,.0f}) at minimal internal delivery cost.\n"
            f"- 'localised_package': Place-based regional ecosystem option delivering 100% - 105% of target (~£{target_sv_gbp:,.0f}) with accredited regional partners.\n"
            f"- 'enhanced_package': Ambitious winning bid proposal delivering 110% - 120% of target (~£{target_sv_gbp * 1.15:,.0f}) to maximize competitive win-rate.\n\n"
            "CRITICAL RULES:\n"
            "1. You MUST read ALL previous conversation turns carefully and incorporate ALL feedback given across turns.\n"
            "2. Adapt initiative themes and titles so they directly address client priorities (e.g. healthcare digital literacy clinics, health-tech apprenticeships).\n"
            "3. Operational Metrics: Explicitly specify sessions_per_year, hours_per_session and participants_per_session for every initiative.\n"
            "4. Commercial Delivery Cost: Provide realistic benchmark delivery costs and summarize commercial trade-offs in commercial_viability_summary so the bid team can compare options.\n"
            "5. Return ONLY valid JSON matching the exact schema requested with keys: core_package, enhanced_package, localised_package, assumptions, validation_required."
        )

        # Build the full messages array with real conversation history
        messages = [{"role": "system", "content": system_prompt}]
        for turn in conversation_turns:
            messages.append({"role": turn["role"], "content": turn["content"]})

        # 1. Google Gemini (flattens multi-turn into single context block)
        if provider == "gemini" and settings.is_gemini_configured:
            try:
                # Gemini REST doesn't support proper multi-turn roles in the same way,
                # so we flatten the thread into a rich single prompt
                full_context = system_prompt + "\n\n=== FULL CONVERSATION THREAD ===\n"
                for turn in conversation_turns:
                    role_label = "BID AUTHOR" if turn["role"] == "user" else "AI PREVIOUS RESPONSE"
                    full_context += f"\n[{role_label}]:\n{turn['content']}\n"
                full_context += "\n=== END THREAD ===\n\nNow generate the improved Social Value proposal JSON:"

                url = (
                    f"https://generativelanguage.googleapis.com/v1beta/models/"
                    f"{settings.GEMINI_MODEL}:generateContent?key={settings.GEMINI_API_KEY}"
                )
                payload = {
                    "contents": [{"parts": [{"text": full_context}]}],
                    "generationConfig": {"temperature": 0.2, "maxOutputTokens": 4096}
                }
                with httpx.Client(timeout=25.0) as client:
                    r = client.post(url, json=payload)
                    if r.status_code == 200:
                        raw = r.json()["candidates"][0]["content"]["parts"][0]["text"].strip()
                        if "```json" in raw:
                            raw = raw.split("```json", 1)[1].split("```", 1)[0].strip()
                        elif "```" in raw:
                            raw = raw.split("```", 1)[1].split("```", 1)[0].strip()
                        data = json.loads(raw)
                        data["is_mock"] = False
                        return data
                    else:
                        err_snippet = r.text[:300]
                        print(f"[LLMService] Gemini conversation HTTP {r.status_code}: {err_snippet}")
                        raise RuntimeError(f"Gemini Refinement API Error ({r.status_code}): {err_snippet}")
            except Exception as e:
                print(f"[LLMService] Gemini refinement unavailable: {e}. Checking fallback options...")
                if settings.is_openai_configured:
                    try:
                        print("[LLMService] Falling back to OpenAI refinement...")
                        response = self.openai_client.chat.completions.create(
                            model=settings.OPENAI_CHAT_MODEL,
                            response_format={"type": "json_object"},
                            messages=messages,
                            temperature=0.2,
                            max_tokens=4000
                        )
                        return json.loads(response.choices[0].message.content)
                    except Exception as oai_err:
                        print(f"[LLMService] OpenAI refinement also failed: {oai_err}")

                print("[LLMService] Engaging Verified Deterministic TOMs Fallback for refinement...")
                fallback_data = self._generate_offline_fallback(opportunity, context_text)
                fallback_data["is_fallback_mode"] = True
                fallback_data["fallback_reason"] = f"AI Provider quota or rate limit reached ({str(e)[:120]})."
                return fallback_data

        # 2. OpenAI — native multi-turn messages support
        if provider == "openai" and settings.is_openai_configured:
            try:
                response = self.openai_client.chat.completions.create(
                    model=settings.OPENAI_CHAT_MODEL,
                    response_format={"type": "json_object"},
                    messages=messages,
                    temperature=0.2,
                    max_tokens=4000
                )
                return json.loads(response.choices[0].message.content)
            except Exception as e:
                print(f"[LLMService] OpenAI conversation error: {e}. Falling back to deterministic engine...")
                fallback_data = self._generate_offline_fallback(opportunity, context_text)
                fallback_data["is_fallback_mode"] = True
                return fallback_data

        # 3. Offline fallback (only if offline explicitly selected or fallback)
        return self._generate_offline_fallback(opportunity, context_text)


